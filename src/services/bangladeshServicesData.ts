const FAVORITES_STORAGE_KEY = 'motherland_bangladesh_favorites';
const RECENT_STORAGE_KEY = 'motherland_bangladesh_recent';

export function getFavoriteServiceIds(): string[] {
  if (typeof window === 'undefined') return ['gov_nid', 'edu_board_results', 'transport_railway'];
  try {
    const raw = localStorage.getItem(FAVORITES_STORAGE_KEY);
    return raw ? JSON.parse(raw) : ['gov_nid', 'edu_board_results', 'transport_railway'];
  } catch {
    return ['gov_nid', 'edu_board_results', 'transport_railway'];
  }
}

export function toggleFavoriteService(id: string): string[] {
  if (typeof window === 'undefined') return [];
  const current = getFavoriteServiceIds();
  const exists = current.includes(id);
  const updated = exists ? current.filter((x) => x !== id) : [id, ...current];
  try {
    localStorage.setItem(FAVORITES_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed toggling favorite:', e);
  }
  return updated;
}

export function getRecentServiceIds(): string[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(RECENT_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function markServiceVisited(id: string): void {
  if (typeof window === 'undefined') return;
  try {
    const current = getRecentServiceIds();
    const updated = [id, ...current.filter((x) => x !== id)].slice(0, 10);
    localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed saving recent service:', e);
  }
}
